// Applies migrations/<dialect>/*.sql in order, each once, in a transaction, and records it in d1_migrations: the table wrangler
// keeps on D1, so a database exported from D1 (`wrangler d1 export`) and opened here carries on where it was.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { PgDriver } from "@bongsu/core/postgres";
import type { SqliteDb } from "./db";

export function migrate(db: SqliteDb, dir: string): string[] {
  const sqlite = db.sqlite;
  sqlite.exec(`CREATE TABLE IF NOT EXISTS d1_migrations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
  )`);
  const done = new Set(
    (sqlite.prepare("SELECT name FROM d1_migrations").all() as { name: string }[]).map((r) => r.name),
  );
  const applied: string[] = [];
  for (const name of readdirSync(dir)
    .filter((f) => /^\d+_.+\.sql$/.test(f))
    .sort()) {
    if (done.has(name)) continue;
    const sql = readFileSync(join(dir, name), "utf8");
    // Some migrations rebuild tables (create, copy, drop, rename): foreign keys are checked after, as D1 does.
    sqlite.pragma("foreign_keys = OFF");
    try {
      sqlite.transaction(() => {
        sqlite.exec(sql);
        const broken = sqlite.pragma("foreign_key_check") as unknown[];
        if (broken.length) throw new Error(`${name} leaves ${broken.length} broken foreign key(s)`);
        sqlite.prepare("INSERT INTO d1_migrations (name) VALUES (?)").run(name);
      })();
    } finally {
      sqlite.pragma("foreign_keys = ON");
    }
    applied.push(name);
  }
  return applied;
}

/** The same on Postgres: migrations/postgres/*.sql in order, each once, in a transaction, recorded in d1_migrations. */
export async function migratePostgres(driver: PgDriver, dir: string): Promise<string[]> {
  await driver.exec(`CREATE TABLE IF NOT EXISTS d1_migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
  )`);
  const done = new Set((await driver.query("SELECT name FROM d1_migrations", [])).map((r) => r.name as string));
  const applied: string[] = [];
  for (const name of readdirSync(dir)
    .filter((f) => /^\d+_.+\.sql$/.test(f))
    .sort()) {
    if (done.has(name)) continue;
    const sql = readFileSync(join(dir, name), "utf8");
    await driver.transaction(async (tx) => {
      await tx.exec(sql);
      await tx.query("INSERT INTO d1_migrations (name) VALUES ($1)", [name]);
    });
    applied.push(name);
  }
  return applied;
}

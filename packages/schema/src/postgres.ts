// Postgres: the neutral types on Postgres's own. Every name is quoted (some columns, like rate_limits."window", are
// reserved words there). Booleans stay SMALLINT because the app's SQL compares them with 0 and 1; JSON stays text
// because the app reads and writes it whole.
import { type Dialect, schemaSql } from "./ddl";
import { TABLES } from "./tables";
import type { Tables } from "./types";

export const postgres: Dialect = {
  name: "postgres",
  type: {
    id: "TEXT",
    text: "TEXT",
    json: "TEXT",
    int: "INTEGER",
    bigint: "BIGINT",
    real: "DOUBLE PRECISION",
    bool: "SMALLINT",
    timestamp: "BIGINT",
    serial: "BIGINT",
  },
  now: "(EXTRACT(EPOCH FROM now())::BIGINT)",
  quote: (n) => `"${n}"`,
  serial: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
};

export const postgresSchema = (tables: Tables = TABLES) => schemaSql(postgres, tables);
